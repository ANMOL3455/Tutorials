# TYPES OF DATATYPES IN R
a <- 4  # numeric
a1 <- 4.1
class(a) # to know the datatype
class(a1)
typeof(a)
b <- 4L #integer    interger always append with " L "
class(b) 
typeof(b)
c <- "hello world this is R" #character
class(c)
typeof(c)
d <- 'hello' 
class(d) 
typeof(d)
e <- TRUE # logical
class(e)
typeof(e)
f <- 2+3i # complex
class(f) 
typeof(f)

