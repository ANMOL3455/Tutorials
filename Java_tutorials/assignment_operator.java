/*
java has assignment operators and they are :
+= : for addition and storing the data to the same variable
-= : for subtraction and storing the data to the same variable
*= : for multiplication and storing the data to the same variable
/=  :for division and storing the data to the same variable
*/

class assignment_operator{
public static void main(String... args){
	int a = 45;
	System.out.println(a+=1);
	System.out.println(a-=1);
	System.out.println(a*=5);
	System.out.println(a/=1);
}

}
